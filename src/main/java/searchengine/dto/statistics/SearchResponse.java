package searchengine.dto.statistics;

import lombok.Data;

import java.util.List;

/**
 * DTO для ответа REST API с результатами поиска.
 *
 * Используется контроллером поиска
 * для передачи клиенту найденных страниц.
 *
 * Содержит:
 *  - флаг успешности запроса
 *  - количество найденных страниц
 *  - список найденных результатов (SearchResult)
 */
@Data
public class SearchResponse {

    /**
     * Флаг успешности выполнения поиска.
     *
     * true  — поиск выполнен успешно
     * false — произошла ошибка
     */
    private boolean result;

    /**
     * Общее количество найденных страниц,
     * соответствующих запросу.
     */
    private int count;

    /**
     * Список результатов поиска.
     *
     * Каждый элемент содержит:
     *  - URL страницы
     *  - заголовок
     *  - сниппет текста
     *  - оценку релевантности
     */
    private List<SearchResult> data;
}
