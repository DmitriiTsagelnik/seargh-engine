package searchengine.dto.statistics;

import lombok.Data;

/**
 * DTO для ответа REST API со статистикой приложения.
 *
 * Используется контроллером статистики
 * для передачи данных клиенту.
 *
 * Содержит:
 * - результат выполнения запроса
 * - объект со статистическими данными
 *
 * Данный класс не связан с сущностями БД
 * и используется исключительно для обмена данными.
 */
@Data
public class StatisticsResponse {

    /**
     * Флаг успешности выполнения запроса.
     *
     * true  — статистика успешно получена
     * false — произошла ошибка
     */
    private boolean result;

    /**
     * Объект со статистикой приложения.
     *
     * Включает:
     * - общую статистику
     * - детализированную статистику по сайтам
     */
    private StatisticsData statistics;
}
