package searchengine.dto.statistics;

import lombok.Data;

import java.util.List;

/**
 * DTO, содержащий статистические данные приложения.
 *
 * Используется как часть ответа StatisticsResponse
 * и объединяет:
 *  - общую статистику по приложению
 *  - детализированную статистику по каждому сайту
 */
@Data
public class StatisticsData {

    /**
     * Общая статистика по всем сайтам.
     *
     * Содержит агрегированные данные,
     * такие как количество сайтов,
     * страниц и лемм в системе.
     */
    private TotalStatistics total;

    /**
     * Детализированная статистика по сайтам.
     *
     * Каждый элемент списка содержит
     * статистику по одному сайту:
     *  - URL
     *  - имя
     *  - статус индексации
     *  - количество страниц и лемм
     *  - сообщение об ошибке (при наличии)
     */
    private List<DetailedStatisticsItem> detailed;
}
